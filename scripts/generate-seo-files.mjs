// ============================================
// Generates public/sitemap.xml and public/robots.txt from the
// catalogue, and keeps the domain in src/index.html in sync with
// environment.seo.siteUrl.
//
// Runs automatically before every `npm run build` (see "prebuild"
// in package.json), so after changing the domain or adding a
// product you never have to edit these files by hand.
//
//   node scripts/generate-seo-files.mjs
// ============================================

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');
const write = (p, s) => writeFileSync(resolve(root, p), s);

// ── Site URL from the environment file ───────
const env = read('src/environments/environment.ts');
const siteUrl = env.match(/siteUrl:\s*'([^']+)'/)?.[1]?.replace(/\/+$/, '');
if (!siteUrl) throw new Error('Could not find seo.siteUrl in src/environments/environment.ts');

// ── Category ids and product slugs from the catalogue ──
const data = read('src/app/data/products.data.ts');
const productsStart = data.indexOf('export const PRODUCTS');
const ids = (src, key) => [...src.matchAll(new RegExp(`^    ${key}:\\s*'([^']+)'`, 'gm'))].map((m) => m[1]);
const categories = ids(data.slice(0, productsStart), 'id');
const products = ids(data.slice(productsStart), 'slug');

// Photos per product (main photo + gallery), for the image sitemap
const photos = {};
for (const block of data.slice(productsStart).split('\n  {').slice(1)) {
  const slug = block.match(/\n    slug:\s*'([^']+)'/)?.[1];
  if (slug) photos[slug] = [...new Set([...block.matchAll(/'(assets\/images\/products\/[^']+)'/g)].map((m) => m[1]))];
}
if (!categories.length || !products.length) throw new Error('Could not read categories/products from products.data.ts');

// ── sitemap.xml ──────────────────────────────
const today = new Date().toISOString().slice(0, 10);
const entry = (path, changefreq, priority, images = []) =>
  `  <url>\n    <loc>${siteUrl}${path.replace(/&/g, '&amp;')}</loc>\n    <lastmod>${today}</lastmod>\n` +
  `    <changefreq>${changefreq}</changefreq>\n    <priority>${priority}</priority>\n` +
  images.map((src) => `    <image:image><image:loc>${siteUrl}/${src}</image:loc></image:image>\n`).join('') +
  `  </url>`;

const urls = [
  entry('/', 'weekly', '1.0'),
  entry('/products', 'weekly', '0.9'),
  entry('/categories', 'monthly', '0.8'),
  ...categories.map((id) => entry(`/categories/${id}`, 'weekly', '0.8')),
  entry('/about', 'monthly', '0.6'),
  entry('/industries', 'monthly', '0.6'),
  entry('/contact', 'yearly', '0.7'),
  ...products.map((slug) => entry(`/products/${slug}`, 'monthly', '0.7', photos[slug] ?? [])),
];

write(
  'public/sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!-- Generated by scripts/generate-seo-files.mjs — do not edit by hand -->\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n${urls.join('\n')}\n</urlset>\n`,
);

// ── robots.txt ───────────────────────────────
write(
  'public/robots.txt',
  `# Generated by scripts/generate-seo-files.mjs\nUser-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`,
);

// ── index.html: swap the old domain for siteUrl ──
// The canonical link tells us which domain the file currently uses.
const indexPath = 'src/index.html';
const index = read(indexPath);
const current = index.match(/<link rel="canonical" href="(https?:\/\/[^/"]+)/)?.[1];
if (current && current !== siteUrl) {
  write(indexPath, index.split(current).join(siteUrl));
  console.log(`index.html: ${current} → ${siteUrl}`);
}

const imageCount = Object.values(photos).reduce((n, list) => n + list.length, 0);
console.log(`sitemap.xml: ${urls.length} URLs, ${imageCount} images (${categories.length} categories, ${products.length} products) on ${siteUrl}`);
